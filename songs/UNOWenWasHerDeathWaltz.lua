local function decodeBase64(source)
    local alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
    local map = {}
    for i = 1, #alphabet do
        map[alphabet:sub(i, i)] = i - 1
    end

    local output = {}
    local buffer, bits = 0, 0
    for i = 1, #source do
        local c = source:sub(i, i)
        local value = map[c]
        if value then
            buffer = buffer * 64 + value
            bits = bits + 6
            while bits >= 8 do
                bits = bits - 8
                local power = 2 ^ bits
                output[#output + 1] = string.char(math.floor(buffer / power) % 256)
                buffer = buffer % power
            end
        end
    end
    return table.concat(output)
end

local function unpackLZSS(source)
    local output = {}
    local cursor = 1

    while cursor <= #source do
        local flags = string.byte(source, cursor)
        cursor = cursor + 1

        for bit = 0, 7 do
            if cursor > #source then
                break
            end

            local literal = math.floor(flags / (2 ^ bit)) % 2 == 1
            if literal then
                output[#output + 1] = source:sub(cursor, cursor)
                cursor = cursor + 1
            else
                local hi = string.byte(source, cursor)
                local lo = string.byte(source, cursor + 1)
                cursor = cursor + 2

                local packed = hi * 256 + lo
                local offset = math.floor(packed / 16)
                local length = (packed % 16) + 3

                for _ = 1, length do
                    output[#output + 1] = output[#output - offset + 1]
                end
            end
        end
    end

    return table.concat(output)
end

